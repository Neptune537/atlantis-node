//! # Closed Thermodynamic Gyre Loop Integration Test
//!
//! Simulates full cyclic circulation across the Pacific loop:
//! 1. Lemuria (Bio-Edge): Edge telemetry & ZK-Geo commitment generation
//! 2. Atlantis (Compute Core): Compute offload & Coral Escrow verification
//! 3. Solana/Tide Staking: PoH slashing engine verification
//! 4. Olympus (Sub-Polar Apex): Master Epoch notarization & Cryo-HSM block signing
//! 5. Oyashio Return: Cold return state distribution back to Lemuria

use atlantis_protocol::*;
use olympus::{MasterEpochClock, OlympusApexAuthority};
use solana_programs::slashing::{PohSlashingEngine, SlashingEvidence, SlashingOffense};

#[test]
fn test_closed_thermodynamic_gyre_loop() {
    // ------------------------------------------------------------------------
    // STAGE 1: LEMURIA (Bio-Edge Ingress & ZK Geo-Proximity)
    // ------------------------------------------------------------------------
    let edge_did = "did:atlantis:lemuria_edge_sensor_tokyo";
    let client_coord: (f64, f64) = (35.6895, 139.6917); // Tokyo
    let timestamp: u64 = 1730000100;
    let salt = "salt_enclave_2026";

    // Lemuria obfuscates raw GPS using ZkGeoProximityProof
    let quantized_lat = (client_coord.0 * 1000.0).round() as i64;
    let quantized_lon = (client_coord.1 * 1000.0).round() as i64;
    let mut hasher = sha2::Sha256::default();
    use sha2::Digest;
    hasher.update(&quantized_lat.to_le_bytes());
    hasher.update(&quantized_lon.to_le_bytes());
    hasher.update(salt.as_bytes());
    hasher.update(&timestamp.to_le_bytes());
    let commitment_hash = bytes_to_hex(&hasher.finalize());

    assert_eq!(commitment_hash.len(), 64);

    // ------------------------------------------------------------------------
    // STAGE 2: ATLANTIS (Compute Core, Tiering, & Task Verification)
    // ------------------------------------------------------------------------
    let triton_vram_mb = 24000;
    let triton_rtt_ms = 18;
    let triton_temp_c = 64.0;
    let (poh_score, tier) = BioluminescenceTelemetry::evaluate_tier(
        triton_vram_mb,
        triton_rtt_ms,
        triton_temp_c,
    );
    assert_eq!(tier, GyreNodeTier::AbyssalAnchor);
    assert!(poh_score >= 80.0);

    // Compute task result generated by Triton
    let compute_result_payload = b"HZB_OCCLUDED_MESH_BATCH_INDIRECT_COMMANDS";
    let mut result_hasher = sha2::Sha256::default();
    result_hasher.update(compute_result_payload);
    let result_hash = bytes_to_hex(&result_hasher.finalize());

    // ------------------------------------------------------------------------
    // STAGE 3: SOLANA STAKING & POH SLASHING PIPELINE
    // ------------------------------------------------------------------------
    let mut slashing_engine = PohSlashingEngine::new();
    slashing_engine.register_staked_node("did:atlantis:worker_legit", 50_000);
    slashing_engine.register_staked_node("did:atlantis:worker_cheater", 50_000);

    // Cheater submits bad compute proof -> caught and slashed 50%
    let fraud_evidence = SlashingEvidence {
        offender_node_did: "did:atlantis:worker_cheater".to_string(),
        offense: SlashingOffense::ComputationFraud,
        task_or_challenge_id: "task_hzb_culling_4096".to_string(),
        evidence_hash: "0xinvalidproof".to_string(),
        reporter_did: edge_did.to_string(),
        timestamp,
    };
    let slashed = slashing_engine.process_slashing(&fraud_evidence).unwrap();
    assert_eq!(slashed, 25_000);
    assert_eq!(slashing_engine.get_node("did:atlantis:worker_cheater").unwrap().staked_cyan, 25_000);

    // ------------------------------------------------------------------------
    // STAGE 4: OLYMPUS (Sub-Polar Apex Authority & Master Clock)
    // ------------------------------------------------------------------------
    let olympus = OlympusApexAuthority::new();
    let epoch_stamp = olympus.clock.now();
    assert_eq!(epoch_stamp.sequence, 1);

    // State root summarizing the epoch transitions
    let state_merkle_root = format!("0xstate_{}", result_hash);
    let validator_quorum = vec![
        "did:atlantis:triton_abyssal_anchor_primary".to_string(),
        "did:atlantis:olympus:root".to_string(),
    ];

    let cold_block = olympus
        .notarize_cold_return_block(&state_merkle_root, validator_quorum)
        .expect("Cold return notarization must succeed");

    assert_eq!(cold_block.state_merkle_root, state_merkle_root);

    // ------------------------------------------------------------------------
    // STAGE 5: OYASHIO RETURN (Sub-Surface Cold Return Verification at Lemuria)
    // ------------------------------------------------------------------------
    let is_verified = olympus
        .verify_cold_return_block(&cold_block)
        .expect("Verification must pass");
    assert!(is_verified);

    println!("✅ Closed Thermodynamic Gyre Loop verified end-to-end across all 5 nodes.");
}
